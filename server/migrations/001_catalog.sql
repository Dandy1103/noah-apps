CREATE SCHEMA IF NOT EXISTS apps;

CREATE TABLE IF NOT EXISTS apps.schema_migrations (
    version text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS apps.systems (
    repo text PRIMARY KEY CHECK (repo ~ '^noah-[a-z0-9]+(-[a-z0-9]+)*$'),
    name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 40),
    url text NOT NULL DEFAULT '' CHECK (length(url) <= 300),
    audience text NOT NULL CHECK (length(btrim(audience)) BETWEEN 1 AND 40),
    online boolean NOT NULL DEFAULT false,
    sort_order integer NOT NULL CHECK (sort_order >= 0)
);

CREATE TABLE IF NOT EXISTS apps.nav_groups (
    group_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 40),
    app_repo text REFERENCES apps.systems (repo) ON DELETE SET NULL,
    sort_order integer NOT NULL CHECK (sort_order >= 0)
);

CREATE TABLE IF NOT EXISTS apps.nav_sections (
    section_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL REFERENCES apps.nav_groups (group_id) ON DELETE CASCADE,
    title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 40),
    sort_order integer NOT NULL CHECK (sort_order >= 0)
);

CREATE TABLE IF NOT EXISTS apps.nav_links (
    link_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id bigint NOT NULL REFERENCES apps.nav_sections (section_id) ON DELETE CASCADE,
    label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 40),
    app_repo text REFERENCES apps.systems (repo) ON DELETE SET NULL,
    path text NOT NULL DEFAULT '' CHECK (path = '' OR path ~ '^[a-z0-9]+(/[a-z0-9]+)*$'),
    sort_order integer NOT NULL CHECK (sort_order >= 0)
);
